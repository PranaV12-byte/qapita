function inlineText(text: string, keyPrefix: string): React.ReactNode[] {
  const pattern = /(\*\*[^*]+\*\*|__[^_]+__|`[^`]+`|\[[^\]]+\]\([^)]+\))/g;
  const parts = text.split(pattern);
  return parts.filter((part) => part.length > 0).map((part, index) => {
    const key = `${keyPrefix}-${index}`;
    if ((part.startsWith("**") && part.endsWith("**")) || (part.startsWith("__") && part.endsWith("__"))) {
      return <Text key={key} style={styles.bold}>{part.slice(2, -2)}</Text>;
    }
    if (part.startsWith("`") && part.endsWith("`")) return <Text key={key}>{part.slice(1, -1)}</Text>;
    const link = part.match(/^\[([^\]]+)\]\([^)]+\)$/);
    return <Text key={key}>{link?.[1] ?? part}</Text>;
  });
}

function InlineText({ text, style, keyPrefix, orphans, widows }: {
  text: string;
  style: Style | Style[];
  keyPrefix: string;
  orphans?: number;
  widows?: number;
}) {
  // Plain lines should stay as one native Text node. Nested Text nodes are
  // only needed when the Markdown parser has an inline style to preserve.
  if (!/(\*\*[^*]+\*\*|__[^_]+__|`[^`]+`|\[[^\]]+\]\([^)]+\))/.test(text)) {
    return <Text style={style} orphans={orphans} widows={widows}>{text}</Text>;
  }
  return <Text style={style} orphans={orphans} widows={widows}>{inlineText(text, keyPrefix)}</Text>;
}

function renderList(block: Extract<PdfBlock, { kind: "list" }>, key: string) {
  return (
    <View key={key} style={styles.list}>
      {block.items.map((item, index) => (
        <View key={`${key}-${index}`} style={styles.listItem} wrap={item.length > 700}>
          <Text style={styles.bullet}>{block.ordered ? `${index + 1}.` : "•"}</Text>
          <InlineText text={item} style={styles.listText} keyPrefix={`${key}-${index}`} orphans={2} widows={2} />
        </View>
      ))}
    </View>
  );
}

function tableTextLength(value: string): number {
  return value
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/__([^_]+)__/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .length;
}

function estimateTableRowHeight(headers: string[], row: string[]): number {
  const topicCount = Math.max(1, headers.length - 1);
  const featureLines = Math.max(1, Math.ceil(tableTextLength(row[0] ?? "") / 22));
  const topicCharsPerLine = Math.max(18, Math.floor(46 / topicCount));
  const topicLines = row.slice(1).map((cell) => Math.max(1, Math.ceil(tableTextLength(cell) / topicCharsPerLine)));
  return 22 + Math.max(featureLines, ...topicLines, 1) * 14.75;
}

function splitTableRows(table: PdfTable, maxHeight = TABLE_PAGE_BUDGET): PdfTable[] {
  const segments: PdfTable[] = [];
  let rows: string[][] = [];
  let usedHeight = TABLE_HEADER_HEIGHT;

  const flush = () => {
    if (!rows.length) return;
    segments.push({ headers: table.headers, rows });
    rows = [];
    usedHeight = TABLE_HEADER_HEIGHT;
  };

  for (const row of table.rows) {
    const rowHeight = estimateTableRowHeight(table.headers, row);
    if (rows.length > 0 && usedHeight + rowHeight > maxHeight) flush();
    rows.push(row);
    usedHeight += rowHeight;
  }
  flush();
  return segments.length ? segments : [{ headers: table.headers, rows: [] }];
}

function renderTable(table: PdfTable, key: string) {
  return (
    <View key={key} style={styles.table} wrap={false}>
      <View style={styles.tableRow}>
        {table.headers.map((header, index) => (
          <Text key={`${key}-head-${index}`} style={index === 0 ? [styles.tableHeader, styles.tableFeature] : [styles.tableHeader, styles.tableCell, index % 2 === 1 ? styles.tableHeaderTopicA : styles.tableHeaderTopicB]}>{header}</Text>
        ))}
      </View>
      {table.rows.map((row, rowIndex) => (
        <View key={`${key}-row-${rowIndex}`} style={styles.tableRow} wrap={false}>
          {row.map((cell, cellIndex) => (
            <InlineText key={`${key}-${rowIndex}-${cellIndex}`} text={cell} style={cellIndex === 0 ? styles.tableFeature : [styles.tableCell, cellIndex % 2 === 1 ? styles.tableCellTopicA : styles.tableCellTopicB]} keyPrefix={`${key}-${rowIndex}-${cellIndex}`} />
          ))}
        </View>
      ))}
    </View>
  );
}

function renderTableSegments(table: PdfTable, key: string): React.ReactNode {
  const segments = splitTableRows(table);
  return (
    <React.Fragment key={key}>
      {segments.map((segment, index) => (
        <React.Fragment key={`${key}-segment-${index}`}>
          {index > 0 ? <View break /> : null}
          {renderTable(segment, `${key}-segment-${index}`)}
        </React.Fragment>
      ))}
    </React.Fragment>
  );
}

function renderBlock(block: PdfBlock, key: string, firstHeading = false): React.ReactNode {
  if (block.kind === "heading") return <View key={key} style={firstHeading ? [styles.heading, styles.firstHeading] : styles.heading} minPresenceAhead={72} wrap={false}><Text style={styles.headingText}>{block.text}</Text></View>;
  if (block.kind === "paragraph") return <InlineText keyPrefix={key} key={key} text={block.text} style={styles.paragraph} orphans={2} widows={2} />;
  if (block.kind === "list") return renderList(block, key);
  if (block.kind === "callout") return <View key={key} style={styles.callout} wrap={block.text.length > 700}><InlineText text={block.text} style={styles.calloutText} keyPrefix={key} orphans={2} widows={2} /></View>;
  return renderTableSegments(block.table, key);
}

function renderBlocks(blocks: PdfBlock[]) {
  return blocks.map((block, index) => renderBlock(block, `block-${index}`, block.kind === "heading" && index === 0));
}

function comparisonTable(data: ComparisonData, topicIndexes: number[], rows: ComparisonData["rows"], key: string) {
  const columns = ["Feature", ...topicIndexes.map((index) => data.columns[index])];
  return (
    <View key={key} style={styles.table} wrap={false}>
      <View style={styles.tableRow}>
        {columns.map((column, index) => (
          <Text key={`${key}-header-${index}`} style={index === 0 ? [styles.tableFeature, styles.tableHeader] : [styles.tableCell, styles.tableHeader, index % 2 === 1 ? styles.tableHeaderTopicA : styles.tableHeaderTopicB]}>{column}</Text>
        ))}
      </View>
      {rows.map((row, rowIndex) => (
        <View key={`${key}-row-${rowIndex}`} style={styles.tableRow} wrap={false}>
          <Text style={styles.tableFeature}>{row.feature}</Text>
          {topicIndexes.map((topicIndex, valueIndex) => (
            <InlineText key={`${key}-cell-${rowIndex}-${valueIndex}`} text={row.values[topicIndex]} style={[styles.tableCell, valueIndex % 2 === 0 ? styles.tableCellTopicA : styles.tableCellTopicB]} keyPrefix={`${key}-${rowIndex}-${valueIndex}`} />
          ))}
        </View>
      ))}
    </View>
  );
}

type ComparisonPage = {
  topicIndexes: number[];
  rows: ComparisonData["rows"];
  includeTakeaway?: boolean;
};

/** One table sequence per Page keeps both column headers and document branding
 * present on every comparison continuation page. */
function paginateComparison(data: ComparisonData): ComparisonPage[] {
  const topicGroups: number[][] = [];
  for (let index = 0; index < data.columns.length; index += 2) topicGroups.push([index, ...([index + 1].filter((item) => item < data.columns.length))]);
  const pages: ComparisonPage[] = [];
  let pageIndex = 0;
  for (const topicIndexes of topicGroups) {
    const table = {
      headers: ["Feature", ...topicIndexes.map((index) => data.columns[index])],
      rows: data.rows.map((row) => [row.feature, ...topicIndexes.map((index) => row.values[index])]),
    };
    const segments = splitTableRows(table, pageIndex === 0 ? COMPARISON_FIRST_PAGE_BUDGET : TABLE_PAGE_BUDGET);
    let rowOffset = 0;
    for (const segment of segments) {
      pages.push({ topicIndexes, rows: data.rows.slice(rowOffset, rowOffset + segment.rows.length) });
      rowOffset += segment.rows.length;
      pageIndex += 1;
    }
  }

  if (pages.length) {
    const last = pages[pages.length - 1]!;
    const lastTable = {
      headers: ["Feature", ...last.topicIndexes.map((index) => data.columns[index])],
      rows: last.rows.map((row) => [row.feature, ...last.topicIndexes.map((index) => row.values[index])]),
    };
    const available = pages.length === 1 ? COMPARISON_FIRST_PAGE_BUDGET : TABLE_PAGE_BUDGET;
    const calloutHeight = 32 + Math.max(1, Math.ceil(tableTextLength(data.takeaway) / 76)) * 15;
    const tableHeight = TABLE_HEADER_HEIGHT + lastTable.rows.reduce((total, row) => total + estimateTableRowHeight(lastTable.headers, row), 0);
    if (tableHeight + calloutHeight + CALLOUT_RESERVE > available && last.rows.length > 1) {
      const moved = last.rows.pop()!;
      pages.push({ topicIndexes: last.topicIndexes, rows: [moved], includeTakeaway: true });
    } else {
      last.includeTakeaway = true;
    }
  }
  return pages;
}

function renderComparisonPage(data: ComparisonData, page: ComparisonPage, pageIndex: number) {
  return <>
    {page.rows.length > 0 ? comparisonTable(data, page.topicIndexes, page.rows, `comparison-table-${pageIndex}`) : null}
    {page.includeTakeaway ? (
      <View key="comparison-takeaway" style={styles.callout} wrap={false}>
      <Text style={{ color: "#7C3AED", fontSize: 12, fontWeight: 700, letterSpacing: 0.5, marginBottom: 6 }}>Bottom Line</Text>
      <InlineText text={data.takeaway} style={styles.calloutText} keyPrefix="comparison-takeaway-text" />
      </View>
    ) : null}
  </>;
}

function BrandGradient({ height, style }: { height: number; style: Style }): React.ReactElement {
  // React-PDF renders a LinearGradient supplied directly as a shape fill, but
  // its Rect type currently advertises only string fills. Keep the runtime
  // gradient object intact while narrowing the library's stale declaration.
  const gradient = (
    <LinearGradient id="equityiq-brand-gradient" x1={0} y1={0} x2={1} y2={0} gradientUnits="objectBoundingBox">
      <Stop offset={0} stopColor="#1C1B2E" />
      <Stop offset={0.5} stopColor="#2D2A4A" />
      <Stop offset={1} stopColor="#1C1B2E" />
    </LinearGradient>
  );
  return (
    <Svg width={PAGE_WIDTH} height={height} viewBox={`0 0 ${PAGE_WIDTH} ${height}`} preserveAspectRatio="none" style={style}>
      <Rect
        x={0}
        y={0}
        width={PAGE_WIDTH}
        height={height}
        fill={gradient as unknown as string}
      />
    </Svg>
  );
}

