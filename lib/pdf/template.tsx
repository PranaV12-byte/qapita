type Props = {
  title: string;
  question: string;
  bodyMarkdown: string;
  blocks: PdfBlock[];
  comparison?: ComparisonData;
  date: string;
  nasppLogoSrc: string;
  qapitaLogoSrc: string;
};

export function EquityBriefPDF({ title, question, blocks, comparison, date, nasppLogoSrc, qapitaLogoSrc }: Props) {
  const showTitle = !isRedundantArtifactTitle(title, question);
  return (
    <Document>
      <Page size="LETTER" style={styles.page} wrap>
        <View style={styles.question}>
          <Text style={styles.questionLabel}>Your Question</Text>
          <Text style={styles.questionText}>{question}</Text>
        </View>

        {showTitle ? <Text style={styles.title}>{title}</Text> : null}
        {comparison ? renderComparison(comparison) : renderBlocks(blocks)}

        <View fixed wrap={false} style={styles.header} render={() => <HeaderContent date={date} nasppLogoSrc={nasppLogoSrc} qapitaLogoSrc={qapitaLogoSrc} />} />

        <View fixed wrap={false} style={styles.footer} render={() => <FooterContent nasppLogoSrc={nasppLogoSrc} qapitaLogoSrc={qapitaLogoSrc} />} />
      </Page>
    </Document>
  );
}
