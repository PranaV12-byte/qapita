export function EquityBriefPDF({ title, question, blocks, comparison, date, nasppLogoSrc, qapitaLogoSrc, fontFamily }: Props) {
  const showTitle = !isRedundantArtifactTitle(title, question);
  const comparisonPages = comparison ? paginateComparison(comparison) : null;
  if (!comparison || !comparisonPages) {
    return (
      <Document>
        <Page size="LETTER" style={[styles.page, { fontFamily }]} wrap>
          <PageBranding date={date} nasppLogoSrc={nasppLogoSrc} qapitaLogoSrc={qapitaLogoSrc} />
          <View style={styles.question}>
            <Text style={styles.questionLabel}>Your Question</Text>
            <Text style={styles.questionText}>{question}</Text>
          </View>
          {showTitle ? <Text style={styles.title}>{title}</Text> : null}
          {renderBlocks(blocks)}
        </Page>
      </Document>
    );
  }

  return (
    <Document>
      {comparisonPages.map((page, pageIndex) => (
        <Page key={`page-${pageIndex}`} size="LETTER" style={[styles.page, { fontFamily }]} wrap>
          <PageBranding date={date} nasppLogoSrc={nasppLogoSrc} qapitaLogoSrc={qapitaLogoSrc} />

          {pageIndex === 0 ? (
            <>
              <View style={styles.question}>
                <Text style={styles.questionLabel}>Your Question</Text>
                <Text style={styles.questionText}>{question}</Text>
              </View>
              {showTitle ? <Text style={styles.title}>{title}</Text> : null}
            </>
          ) : null}
          {renderComparisonPage(comparison, page, pageIndex)}
        </Page>
      ))}
    </Document>
  );
}
