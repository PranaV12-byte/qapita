function inlineText(text: string, keyPrefix: string): React.ReactNode[] {
  const pattern = /(\*\*[^*]+\*\*|__[^_]+__|`[^`]+`|\[[^\]]+\]\([^)]+\))/g;
  const parts = text.split(pattern);
  return parts.filter((part) => part.length > 0).map((part, index) => {
    const key = `${keyPrefix}-${index}`;
    if ((part.startsWith("**") && part.endsWith("**")) || (part.startsWith("__") && part.endsWith("__"))) {
      return <Text key={key} style={styles.bold}>{part.slice(2, -2)}</Text>;
    }
    if (part.startsWith("`") && part.endsWith("`")) return <Text key={key}>{part.slice(1, -1)}</Text>;
    const link = part.match(/^\[([^\]]+)\]\([^)]+\)$/);
    return <Text key={key}>{link?.[1] ?? part}</Text>;
  });
}

function InlineText({ text, style, keyPrefix }: { text: string; style: Style | Style[]; keyPrefix: string }) {
  return <Text style={style}>{inlineText(text, keyPrefix)}</Text>;
}

function renderList(block: Extract<PdfBlock, { kind: "list" }>, key: string) {
  return (
    <View key={key} style={styles.list}>
      {block.items.map((item, index) => (
        <View key={`${key}-${index}`} style={styles.listItem}>
          <Text style={styles.bullet}>{block.ordered ? `${index + 1}.` : "•"}</Text>
          <InlineText text={item} style={styles.listText} keyPrefix={`${key}-${index}`} />
        </View>
      ))}
    </View>
  );
}

function renderTable(table: PdfTable, key: string) {
  return (
    <View key={key} style={styles.table} wrap={false}>
      <View style={styles.tableRow}>
        {table.headers.map((header, index) => (
          <Text key={`${key}-head-${index}`} style={index === 0 ? [styles.tableHeader, styles.tableFeature] : [styles.tableHeader, styles.tableCell, index % 2 === 1 ? styles.tableHeaderTopicA : styles.tableHeaderTopicB]}>
            {header}
          </Text>
        ))}
      </View>
      {table.rows.map((row, rowIndex) => (
        <View key={`${key}-row-${rowIndex}`} style={styles.tableRow} wrap={false}>
          {row.map((cell, cellIndex) => (
            <InlineText key={`${key}-${rowIndex}-${cellIndex}`} text={cell} style={cellIndex === 0 ? styles.tableFeature : [styles.tableCell, cellIndex % 2 === 1 ? styles.tableCellTopicA : styles.tableCellTopicB]} keyPrefix={`${key}-${rowIndex}-${cellIndex}`} />
          ))}
        </View>
      ))}
    </View>
  );
}

function renderBlock(block: PdfBlock, key: string, firstHeading = false): React.ReactNode {
  if (block.kind === "heading") return <View key={key} style={firstHeading ? [styles.heading, styles.firstHeading] : styles.heading} minPresenceAhead={32} wrap={false}><Text style={styles.headingText}>{block.text}</Text></View>;
  if (block.kind === "paragraph") return <InlineText keyPrefix={key} key={key} text={block.text} style={styles.paragraph} />;
  if (block.kind === "list") return renderList(block, key);
  if (block.kind === "callout") return <View key={key} style={styles.callout} wrap={false}><InlineText text={block.text} style={styles.calloutText} keyPrefix={key} /></View>;
  return renderTable(block.table, key);
}

function renderBlocks(blocks: PdfBlock[]) {
  return blocks.map((block, index) => renderBlock(block, `block-${index}`, block.kind === "heading" && index === 0));
}

function comparisonTable(data: ComparisonData, topicIndexes: number[], rows: ComparisonData["rows"], key: string) {
  const columns = ["Feature", ...topicIndexes.map((index) => data.columns[index])];
  return (
    <View key={key} style={styles.table} wrap={false}>
      <View style={styles.tableRow}>
        {columns.map((column, index) => (
          <Text key={`${key}-header-${index}`} style={index === 0 ? [styles.tableFeature, styles.tableHeader] : [styles.tableCell, styles.tableHeader, index % 2 === 1 ? styles.tableHeaderTopicA : styles.tableHeaderTopicB]}>{column}</Text>
        ))}
      </View>
      {rows.map((row, rowIndex) => (
        <View key={`${key}-row-${rowIndex}`} style={styles.tableRow} wrap={false}>
          <Text style={styles.tableFeature}>{row.feature}</Text>
          {topicIndexes.map((topicIndex, valueIndex) => (
            <InlineText key={`${key}-cell-${rowIndex}-${valueIndex}`} text={row.values[topicIndex]} style={[styles.tableCell, valueIndex % 2 === 0 ? styles.tableCellTopicA : styles.tableCellTopicB]} keyPrefix={`${key}-${rowIndex}-${valueIndex}`} />
          ))}
        </View>
      ))}
    </View>
  );
}

function renderComparison(data: ComparisonData) {
  const topicGroups: number[][] = [];
  for (let index = 0; index < data.columns.length; index += 2) topicGroups.push([index, ...([index + 1].filter((item) => item < data.columns.length))]);
  const sequences: React.ReactNode[] = [];
  let sequenceIndex = 0;
  for (const topicIndexes of topicGroups) {
    const pageSize = sequenceIndex === 0 ? 2 : 3;
    for (let rowIndex = 0; rowIndex < data.rows.length; rowIndex += pageSize) {
      const rows = data.rows.slice(rowIndex, rowIndex + pageSize);
      sequences.push(
        <View key={`comparison-${sequenceIndex}`} break={sequenceIndex > 0}>
          {comparisonTable(data, topicIndexes, rows, `comparison-table-${sequenceIndex}`)}
        </View>
      );
      sequenceIndex += 1;
    }
  }
  sequences.push(
    <View key="comparison-takeaway" style={styles.callout} wrap={false}>
      <Text style={{ color: "#7C3AED", fontSize: 12, fontWeight: 700, letterSpacing: 0.5, marginBottom: 6 }}>Bottom Line</Text>
      <InlineText text={data.takeaway} style={styles.calloutText} keyPrefix="comparison-takeaway-text" />
    </View>
  );
  return sequences;
}

type PdfPainter = {
  fillColor: (color: string) => PdfPainter;
  rect: (x: number, y: number, width: number, height: number) => PdfPainter;
  fill: () => PdfPainter;
};

function paintBrandGradient(painter: PdfPainter, width: number, height: number): null {
  const start = [0x1c, 0x1b, 0x2e];
  const middle = [0x2d, 0x2a, 0x4a];
  const bands = 64;
  const segmentWidth = width / bands;
  for (let index = 0; index < bands; index += 1) {
    const position = index / (bands - 1);
    const progress = position <= 0.5 ? position * 2 : (position - 0.5) * 2;
    const from = position <= 0.5 ? start : middle;
    const to = position <= 0.5 ? middle : start;
    const color = `#${from.map((channel, channelIndex) => Math.round(channel + (to[channelIndex] - channel) * progress).toString(16).padStart(2, "0")).join("")}`;
    painter.fillColor(color).rect(index * segmentWidth, 0, segmentWidth + 0.5, height).fill();
  }
  return null;
}

