/**
 * Each render receives an isolated font source. React-PDF mutates its font
 * subset while producing a document, so reusing one source can corrupt text
 * in later PDFs within the same warm server process.
 */
export function registerPdfFontFamily(family: string): void {
  Font.register({
    family,
    // React-PDF's fontkit subsetter cannot reliably embed the variable WOFF2
    // emitted by next/font. These local static faces keep PDF generation
    // deterministic and preserve the supplied typography hierarchy.
    fonts: [
      { src: interRegularFont, fontWeight: 400 },
      { src: interBoldFont, fontWeight: 500 },
      { src: interBoldFont, fontWeight: 600 },
      { src: interBoldFont, fontWeight: 700 },
    ],
  });
}

